"""Build English item-name search lookup from the same tables as the mod."""
from pathlib import Path
import csv,json,sys,re

def generate(root,output):
 root=Path(root)/'data';strings={};ids={}
 for f in (root/'local/lng/strings').glob('*.json'):
  for r in json.loads(f.read_text(encoding='utf-8-sig')):
   if 'Key' in r:
    strings[r['Key']]=r.get('enUS',r['Key'])
    if 'id' in r:ids[r['Key']]=r['id']
 def rows(name):return list(csv.DictReader((root/'global/excel'/name).open(encoding='utf-8-sig'),delimiter='\t'))
 def quote(s):
  s=re.sub(r'(?:ÿ|\*|\\xff)c.', '', s)
  return json.dumps(' '.join(s.split()),ensure_ascii=True)
 lines=['// Generated by stash_organizer_catalog.py. English names plus item codes.','struct CatalogEntry {unsigned key;const char* name;int width,height,sortGroup;};','inline constexpr CatalogEntry BaseNames[]={']
 for table in ['armor.txt','weapons.txt','misc.txt']:
  for r in rows(table):
   code=r.get('code','')
   if not code or len(code)>4:continue
   key=int.from_bytes(code.encode('ascii').ljust(4,b' '),'little')
   name=strings.get(r.get('namestr',''),r.get('name',code))
   typ=r.get('type','')
   group=0 if typ=='book' else 1 if typ in ('scha','mcha','lcha','char') else 2 if code=='box' else 3 if typ.startswith('gem') or typ in ('rune','runx','orbx','herb','cjwl','csch','wtrl') else 4
   lines.append('{'+str(key)+','+quote(name)+','+str(int(r.get('invwidth') or 1))+','+str(int(r.get('invheight') or 1))+','+str(group)+'},')
 lines.append('};')
 for table,label in [('uniqueitems.txt','UniqueNames'),('setitems.txt','SetNames')]:
  lines.append('inline constexpr const char* '+label+'[]={')
  for r in rows(table):
   # Expansion is a loader directive, not a compiled item record. Other
   # unused/dummy rows DO occupy IDs and must remain in the lookup.
   if r.get('index','').strip().casefold()=='expansion':continue
   lines.append(quote(strings.get(r.get('index',''),r.get('index','')))+',')
  lines.append('};')
 lines.append('struct RunewordName {unsigned id;const char* name;}; inline constexpr RunewordName RunewordNames[]={')
 for r in rows('runes.txt'):
  key=r.get('Name','')
  if key in ids:lines.append('{'+str(ids[key])+','+quote(strings.get(key,key))+'},')
 lines.append('};')
 lines.append('struct SearchStat {int id;const char* positive;const char* negative;}; inline constexpr SearchStat SearchStats[]={')
 for index,r in enumerate(rows('itemstatcost.txt')):
  positive=strings.get(r.get('descstrpos',''),'')
  negative=strings.get(r.get('descstrneg',''),positive)
  if positive:lines.append('{'+str(int(r.get('*ID') or index))+','+quote(positive)+','+quote(negative)+'},')
 lines.append('};')
 from stash_organizer_ui import layout
 data=json.dumps(layout(),separators=(',',':'))
 lines.append('inline constexpr char OrganizerLayout[]=')
 lines.extend(json.dumps(data[i:i+4000]) for i in range(0,len(data),4000))
 lines.append(';')
 Path(output).write_text('\n'.join(lines),encoding='utf-8')
if __name__=='__main__':generate(sys.argv[1],sys.argv[2])
